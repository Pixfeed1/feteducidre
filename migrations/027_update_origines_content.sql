<h2>Pourquoi cette longévité ?</h2>

<p>La fête du cidre est née il y a plus de quarante ans. À l''époque, c''était une foire au cidre qui regroupait quelques producteurs. L''idée simple et géniale était de faire vivre le village autrement et de faire valoir le cidre, production de notre terroir.</p>

<p>Quarante ans plus tard, la motivation des habitants est toujours réelle, mieux, elle se renouvelle avec les générations. Les acteurs d''hier, devenus grands-parents, œuvrent aux côtés de leurs petits-enfants.</p>

<p><strong>L''envie de faire vivre son village différemment</strong> est au premier rang : l''Hôtellerie de Flée ne serait pas ce qu''elle est sans cette fête. Chacun a à cœur de poursuivre cette œuvre.</p>

<p>Cette fête joue le rôle de ciment social entre les habitants, parfois seule occasion de se côtoyer. Les habitants se saluent, se respectent du fait de cette participation à la fête. C''est un moment où toutes les catégories professionnelles sont mélangées dans un même et seul objectif : faire que la fête soit réussie.</p>

<p>C''est une fierté de participer à cette journée au-delà des préparatifs et des aléas liés à ce genre d''organisation.</p>

